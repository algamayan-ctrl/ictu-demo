<?php

namespace App\Reports\Exporters;

use App\Reports\ReportScopeFormatter;
use App\Reports\ReportDataset;
use App\Reports\ReportExportOptions;
use App\Reports\ReportSummaryFormatter;
use App\Reports\ReportSignatories;
use Carbon\Carbon;
use PhpOffice\PhpSpreadsheet\Cell\DataType;
use PhpOffice\PhpSpreadsheet\Spreadsheet;
use PhpOffice\PhpSpreadsheet\RichText\RichText;
use PhpOffice\PhpSpreadsheet\Shared\Drawing;
use PhpOffice\PhpSpreadsheet\Shared\Font as FontMetrics;
use PhpOffice\PhpSpreadsheet\Style\Alignment;
use PhpOffice\PhpSpreadsheet\Style\Font;
use PhpOffice\PhpSpreadsheet\Style\Fill;
use PhpOffice\PhpSpreadsheet\Writer\Xlsx;

/**
 * A genuine .xlsx workbook of the report.
 *
 * The spreadsheet is data, not a picture of a document: no seal, no rules, no
 * decoration. Numbers are written as numbers and dates as real dates so the
 * recipient can sort, filter and total them, which is the only reason to hand
 * someone a spreadsheet rather than a PDF.
 */
class SpreadsheetExporter
{
    /**
     * The two date shapes the report builders produce. Nothing else is
     * treated as a date, so a purpose or a remark can never be reinterpreted
     * as one.
     */
    private const DATE_FORMATS = [
        'd/m/Y h:i A' => 'dd/mm/yyyy hh:mm AM/PM',
        'd/m/Y' => 'dd/mm/yyyy',
        'd M Y, g:i A' => 'dd mmm yyyy hh:mm AM/PM',
        'd M Y' => 'dd mmm yyyy',
    ];

    public function render(ReportDataset $dataset, ReportExportOptions $options): string
    {
        $spreadsheet = new Spreadsheet;
        $sheet = $spreadsheet->getActiveSheet();
        $sheet->setTitle($this->sheetTitle($dataset->label));

        $meta = $dataset->meta;
        $row = 1;

        /*
         * A short provenance block so an exported sheet can still be
         * identified once it is separated from the system that produced it.
         */
        $sheet->setCellValue([1, $row++], $dataset->label);
        $sheet->setCellValue([1, $row++], $meta['period_long'] ?? ($meta['period_label'] ?? ''));

        if ($options->includeGeneratedBy && ! empty($meta['generated_by'])) {
            $sheet->setCellValueExplicit([1, $row++], 'Generated by: '.$meta['generated_by'], DataType::TYPE_STRING);
        }

        $sheet->setCellValue([1, $row++], 'Date Generated: '.($meta['generated_long'] ?? ''));

        if ($options->includeFilters) {
            $scopeSummary = implode(' · ', array_column(ReportScopeFormatter::rows($meta['applied_filters'] ?? []), 'value'));

            if ($scopeSummary !== '') {
                $sheet->setCellValue([1, $row++], 'Report Scope: '.$scopeSummary);
            }
        }

        if ($options->includeSummary && ! empty($dataset->summary)) {
            $row++;
            $sheet->setCellValue([1, $row], 'Report Summary');
            $sheet->getStyle([1, $row, 1, $row])->getFont()->setBold(true);
            $row++;

            foreach ($dataset->summary as $label => $value) {
                $sheet->setCellValue([1, $row], $label);
                $numeric = ReportSummaryFormatter::numeric($value);

                if ($numeric !== null) {
                    $sheet->setCellValueExplicit([2, $row], $numeric, DataType::TYPE_NUMERIC);

                    if (ReportSummaryFormatter::isCurrencyLabel((string) $label)) {
                        $sheet->getStyle([2, $row, 2, $row])
                            ->getNumberFormat()
                            ->setFormatCode('₱#,##0.00');
                    }
                } else {
                    $sheet->setCellValue([2, $row], $value);
                }

                $row++;
            }
        }

        $row++;
        $headerRow = $row;

        foreach ($dataset->columns as $index => $column) {
            $sheet->setCellValue([$index + 1, $headerRow], $column['label']);
        }

        $lastColumn = max(1, count($dataset->columns));

        $sheet->getStyle([1, $headerRow, $lastColumn, $headerRow])
            ->getFont()->setBold(true);

        $sheet->getStyle([1, $headerRow, $lastColumn, $headerRow])
            ->getFill()
            ->setFillType(Fill::FILL_SOLID)
            ->getStartColor()->setRGB('EFEFEF');

        $row = $headerRow + 1;

        foreach ($dataset->rows as $record) {
            foreach ($dataset->columns as $index => $column) {
                $this->writeCell(
                    $sheet,
                    $index + 1,
                    $row,
                    (string) ($record[$column['key']] ?? ''),
                    ($column['align'] ?? null) === 'numeric',
                    $dataset->reportKey === 'summary' && in_array($column['key'], ['date_needed', 'received_at', 'released_at'], true)
                );
            }

            $row++;
        }

        /* Freezing below the header keeps the columns readable while scrolling. */
        $sheet->freezePane([1, $headerRow + 1]);

        if ($dataset->count() > 0) {
            $sheet->setAutoFilter([1, $headerRow, $lastColumn, $row - 1]);
        }

        foreach (range(1, $lastColumn) as $column) {
            $sheet->getColumnDimensionByColumn($column)->setAutoSize(true);
        }

        $sheet->getStyle([1, 1, $lastColumn, $row])
            ->getAlignment()
            ->setVertical(Alignment::VERTICAL_TOP);

        $sheet->calculateColumnWidths();
        foreach (range(1, $lastColumn) as $column) {
            $sheet->getColumnDimensionByColumn($column)->setAutoSize(false);
        }
        $this->addSignatories($sheet, $meta, $row + 1, $lastColumn);
        $sheet->getPageSetup()->setFitToWidth(1)->setFitToHeight(0);

        return $this->output($spreadsheet);
    }

    // This is the manual-signature area outside the spreadsheet's record filter range.
    private function addSignatories(\PhpOffice\PhpSpreadsheet\Worksheet\Worksheet $sheet, array $meta, int $row, int $lastColumn): void
    {
        $lastColumn = max(2, $lastColumn);
        $height = 90;
        $font = (new Font)->setSize(10)->setBold(true);
        $defaultFont = $sheet->getParent()->getDefaultStyle()->getFont();
        $widths = [];
        foreach (range(1, $lastColumn) as $column) {
            $widths[$column] = Drawing::cellDimensionToPixels($sheet->getColumnDimensionByColumn($column)->getWidth(), $defaultFont);
        }
        $target = array_sum($widths) / 2;
        $split = 1;
        $leftWidth = 0;
        $difference = PHP_INT_MAX;
        foreach (range(1, $lastColumn - 1) as $column) {
            $leftWidth += $widths[$column];
            if (abs($target - $leftWidth) < $difference) {
                $split = $column;
                $difference = abs($target - $leftWidth);
            }
        }
        $ranges = [[1, $split], [$split + 1, $lastColumn]];

        foreach (array_values(ReportSignatories::fromMeta($meta)) as $index => $signatory) {
            [$first, $last] = $ranges[$index];
            if ($first !== $last) $sheet->mergeCells([$first, $row, $last, $row]);
            $width = 0;
            foreach (range($first, $last) as $column) {
                $width += $widths[$column];
            }
            $width = max(24, $width - 12);
            $line = str_repeat('_', max(3, min(28, (int) floor($width / FontMetrics::getTextWidthPixelsApprox('_', $font)))));
            $text = new RichText;
            $text->createTextRun($signatory['label']."\n\n".$line."\n")->getFont()->setSize(9);
            $text->createTextRun($signatory['name'])->getFont()->setSize(10)->setBold(true)->setUnderline('single');
            $text->createTextRun("\n".$signatory['designation'])->getFont()->setSize(9);
            $sheet->setCellValue([$first, $row], $text);
            $sheet->getStyle([$first, $row, $last, $row])->getAlignment()->setWrapText(true)->setVertical(Alignment::VERTICAL_TOP);
            $height = max($height, 4 + 13 * $this->signatureLineCount($text->getPlainText(), $font, $width));
        }

        $sheet->getRowDimension($row)->setRowHeight($height);
    }

    private function signatureLineCount(string $text, Font $font, int $width): int
    {
        $lines = 0;
        foreach (explode("\n", $text) as $line) {
            $lines++;
            $current = '';
            foreach (preg_split('/\s+/u', trim($line)) ?: [] as $word) {
                $candidate = $current === '' ? $word : $current.' '.$word;
                if ($current !== '' && FontMetrics::getTextWidthPixelsApprox($candidate, $font) > $width) {
                    $lines++;
                    $current = $word;
                } else {
                    $current = $candidate;
                }
                $lines += max(0, (int) ceil(FontMetrics::getTextWidthPixelsApprox($word, $font) / $width) - 1);
            }
        }

        return $lines;
    }

    /**
     * Write one cell, keeping numbers numeric and dates real dates.
     *
     * Values arrive pre-formatted from the dataset, so a value is converted
     * only when it matches one of the shapes the builders emit exactly.
     * Anything else is written as text rather than guessed at.
     */
    private function writeCell(mixed $sheet, int $column, int $row, string $value, bool $numericColumn, bool $summaryDate = false): void
    {
        if ($value === '') {
            return;
        }

        if ($numericColumn && is_numeric(str_replace(',', '', $value))) {
            $sheet->setCellValueExplicit(
                [$column, $row],
                (float) str_replace(',', '', $value),
                DataType::TYPE_NUMERIC
            );

            return;
        }

        foreach (self::DATE_FORMATS as $phpFormat => $excelFormat) {
            if (str_contains($phpFormat, '/') && ! $summaryDate) {
                continue;
            }
            /*
             * createFromFormat throws on a value that does not match, so the
             * attempt is guarded: a purpose or a remark must never be
             * reinterpreted as a date, and must never abort the export.
             */
            try {
                $parsed = Carbon::createFromFormat(($summaryDate ? '!' : '').$phpFormat, $value);
            } catch (\Throwable) {
                continue;
            }

            if ($parsed !== false && $parsed->format($phpFormat) === $value) {
                $sheet->setCellValue(
                    [$column, $row],
                    \PhpOffice\PhpSpreadsheet\Shared\Date::PHPToExcel($parsed)
                );

                $sheet->getStyle([$column, $row, $column, $row])
                    ->getNumberFormat()
                    ->setFormatCode($excelFormat);

                return;
            }
        }

        $sheet->setCellValueExplicit([$column, $row], $value, DataType::TYPE_STRING);
    }

    private function output(Spreadsheet $spreadsheet): string
    {
        $writer = new Xlsx($spreadsheet);

        ob_start();
        $writer->save('php://output');

        return (string) ob_get_clean();
    }

    /** Excel rejects sheet names over 31 characters or carrying []:*?/\ */
    private function sheetTitle(string $label): string
    {
        return mb_substr(
            (string) preg_replace('/[\\\\\\/\\?\\*\\[\\]:]/', ' ', $label),
            0,
            31
        );
    }
}
