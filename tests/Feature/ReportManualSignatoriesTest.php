<?php

namespace Tests\Feature;

use App\Enums\AccessClassification;
use App\Enums\AccountStatus;
use App\Models\AuditEvent;
use App\Models\User;
use App\Reports\ReportDataset;
use App\Reports\ReportExportOptions;
use App\Reports\ReportFilters;
use App\Reports\ReportSignatories;
use App\Services\ReportService;
use Carbon\Carbon;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Storage;
use PhpOffice\PhpSpreadsheet\IOFactory;
use PhpOffice\PhpSpreadsheet\RichText\RichText;
use PHPUnit\Framework\Attributes\DataProvider;
use Tests\TestCase;
use ZipArchive;

class ReportManualSignatoriesTest extends TestCase
{
    use RefreshDatabase;

    private User $officer;
    private User $head;

    protected function setUp(): void
    {
        parent::setUp();
        Storage::fake('local');
        $this->travelTo(Carbon::create(2026, 11, 16, 9));
        $this->officer = User::factory()->create([
            'access_classification' => AccessClassification::SpmuOfficer,
            'full_name' => 'Test Action Officer',
            'designation' => 'Administrative Aide VI',
        ]);
        $this->head = User::factory()->create([
            'access_classification' => AccessClassification::SpmuHead,
            'full_name' => 'Test SPMU Admin',
            'designation' => 'Administrative Officer V / Supply Officer III',
        ]);
    }

    public static function visibleReports(): array
    {
        return array_map(fn ($key) => [$key], ['all-transactions', 'summary', 'inventory', 'utilization', 'accountability-cases', 'billing-settlement']);
    }

    #[DataProvider('visibleReports')]
    public function test_all_six_reports_print_the_designated_roles_once_without_signing(string $report): void
    {
        $page = $this->actingAs($this->head)->withSession(['active_workspace' => 'SPMU'])
            ->get(route('reports.print', ['type' => $report, 'academic_period' => 'month']));
        $page->assertOk()->assertSee('TEST ACTION OFFICER')->assertSee('TEST SPMU ADMIN')
            ->assertSee('Administrative Aide VI')->assertSee('Administrative Officer V / Supply Officer III')
            ->assertSee('Generated by')->assertDontSee('No signature is required');
        $this->assertSame(1, substr_count($page->getContent(), 'aria-label="Report signatories"'));
        $this->assertSame(1, substr_count($page->getContent(), 'Prepared by:'));
        $this->assertSame(1, substr_count($page->getContent(), 'Noted by:'));
        $this->assertDatabaseCount('signature_snapshots', 0);
        $this->assertDatabaseCount('user_signatures', 0);
        $this->assertSame(0, AuditEvent::where('action_code', 'E_SIGNATURE_APPLIED')->count());
    }

    public function test_generation_keeps_generator_and_designated_preparer_as_separate_facts(): void
    {
        $dataset = $this->generate();
        $this->assertSame($this->head->full_name, $dataset->meta['generated_by']);
        $this->assertSame($this->officer->id, $dataset->meta['signatories']['prepared_by']['user_id']);
        $this->assertSame($this->head->id, $dataset->meta['signatories']['noted_by']['user_id']);
        $this->officer->update(['full_name' => 'Updated Officer']);
        $printed = ReportSignatories::fromMeta($dataset->meta);
        $this->assertSame('TEST ACTION OFFICER', $printed['prepared_by']['name']);
        $this->assertSame('UPDATED OFFICER', ReportSignatories::fromMeta($this->generate()->meta)['prepared_by']['name']);
    }

    public function test_inactive_accounts_are_excluded_and_missing_designations_use_role_labels(): void
    {
        User::factory()->create(['access_classification' => AccessClassification::SpmuOfficer, 'account_status' => AccountStatus::Inactive]);
        $this->officer->update(['designation' => null]);
        $printed = ReportSignatories::fromMeta($this->generate()->meta);
        $this->assertSame('TEST ACTION OFFICER', $printed['prepared_by']['name']);
        $this->assertSame('SPMU Action Officer', $printed['prepared_by']['designation']);
        $this->officer->update(['account_status' => AccountStatus::Suspended]);
        $this->assertSame('Signatory not designated', ReportSignatories::fromMeta($this->generate()->meta)['prepared_by']['name']);
    }

    public function test_multiple_active_accounts_never_choose_an_arbitrary_signatory(): void
    {
        User::factory()->create(['access_classification' => AccessClassification::SpmuOfficer]);
        User::factory()->create(['access_classification' => AccessClassification::SpmuHead]);
        $dataset = $this->generate();
        foreach ($dataset->meta['signatories'] as $signatory) {
            $this->assertNull($signatory['user_id']);
            $this->assertSame('ambiguous', $signatory['status']);
        }
        foreach (ReportSignatories::fromMeta($dataset->meta) as $signatory) {
            $this->assertSame('Signatory not designated', $signatory['name']);
        }
    }

    public function test_export_formats_keep_records_unchanged_and_manual_signatures_out_of_csv(): void
    {
        $dataset = $this->fixtureDataset(3);
        $original = $dataset->records();
        $files = $this->exportFixture($dataset, 'manual-report');
        $this->assertSame($original, $dataset->records());
        $this->assertStringStartsWith('%PDF', $files['pdf']);
        $xml = $this->zipPart($files['docx'], 'word/document.xml');
        $document = new \DOMDocument;
        $this->assertTrue($document->loadXML($xml));
        $xpath = new \DOMXPath($document);
        $xpath->registerNamespace('w', 'http://schemas.openxmlformats.org/wordprocessingml/2006/main');
        $this->assertSame(0, $xpath->query('(//w:tbl)[last()]/w:tblPr/w:tblBorders')->length);
        $this->assertSame(1, substr_count($xml, 'Prepared by:'));
        $this->assertSame(1, substr_count($xml, 'Noted by:'));
        $this->assertStringContainsString('TEST ACTION OFFICER', $xml);
        $this->assertStringContainsString('TEST SPMU ADMIN', $xml);
        $this->assertStringContainsString('w:cantSplit', $xml);
        $this->assertStringNotContainsString('No signature is required', $xml);
        $this->assertStringContainsString('NUMPAGES', $this->zipPart($files['docx'], 'word/footer1.xml'));
        $this->assertSame("Item,Quantity,Date\n\"Fixture item 1\",1,16/11/2026\n\"Fixture item 2\",2,16/11/2026\n\"Fixture item 3\",3,16/11/2026\n", $files['csv']);
        $file = tempnam(sys_get_temp_dir(), 'report-manual-xlsx-');
        try {
            file_put_contents($file, $files['xlsx']);
            $sheet = IOFactory::load($file)->getActiveSheet();
            $this->assertSame('A7', $sheet->getFreezePane());
            $this->assertSame('A6:C9', $sheet->getAutoFilter()->getRange());
            $this->assertSame(1.0, $sheet->getCell('B7')->getValue());
            $this->assertSame('n', $sheet->getCell('B7')->getDataType());
            $this->assertLessThan(20, $sheet->getColumnDimension('C')->getWidth(), 'Printed titles must not widen the Date column.');
            $this->assertSame(1, $sheet->getPageSetup()->getFitToWidth());
            $this->assertSame(0, $sheet->getPageSetup()->getFitToHeight());
            $signatories = [];
            foreach (range(1, 3) as $column) {
                $value = $sheet->getCell([$column, 11])->getValue();
                if ($value instanceof RichText) $signatories[] = $value;
            }
            $this->assertCount(2, $signatories);
            [$prepared, $noted] = $signatories;
            $this->assertInstanceOf(RichText::class, $prepared);
            $this->assertStringContainsString('Prepared by:', $prepared->getPlainText());
            $this->assertStringContainsString('TEST ACTION OFFICER', $prepared->getPlainText());
            $this->assertStringContainsString('Noted by:', $noted->getPlainText());
            $this->assertStringContainsString('TEST SPMU ADMIN', $noted->getPlainText());
            $this->assertGreaterThanOrEqual(90, $sheet->getRowDimension(11)->getRowHeight());
        } finally {
            @unlink($file);
        }
        $this->assertDatabaseCount('signature_snapshots', 0);
        $this->assertDatabaseCount('user_signatures', 0);
        $this->assertSame([], Storage::disk('local')->allFiles());
    }

    public function test_empty_and_multipage_outputs_keep_a_single_signatory_block(): void
    {
        foreach ([0 => 'manual-empty', 140 => 'manual-multipage', 25 => 'manual-boundary'] as $rows => $prefix) {
            $files = $this->exportFixture($this->fixtureDataset($rows), $prefix);
            $xml = $this->zipPart($files['docx'], 'word/document.xml');
            $this->assertSame(1, substr_count($xml, 'Prepared by:'));
            $this->assertSame(1, substr_count($xml, 'Noted by:'));
            $this->assertStringStartsWith('%PDF', $files['pdf']);
            if ($rows > 0) $this->assertStringContainsString('Fixture item '.$rows, $xml);
        }
    }

    public function test_long_names_and_xml_characters_are_preserved_as_printed_text(): void
    {
        $this->officer->update(['full_name' => 'Maria Teresa Alexandra Delos Santos & Cruz', 'designation' => 'Administrative Aide VI / Supply & Property Management Unit']);
        $this->head->update(['designation' => 'Administrative Officer V / Supply Officer III & Property Administrator']);
        $dataset = $this->fixtureDataset(2);
        $files = $this->exportFixture($dataset, 'manual-long-names');
        $xml = $this->zipPart($files['docx'], 'word/document.xml');
        $document = new \DOMDocument;
        $this->assertTrue($document->loadXML($xml));
        $this->assertStringContainsString('MARIA TERESA ALEXANDRA DELOS SANTOS & CRUZ', $document->textContent);
        $this->assertStringContainsString('Supply & Property Management Unit', $document->textContent);
        $html = view('reports.document.sheet', ['dataset' => $dataset])->render();
        $this->assertStringContainsString('SANTOS &amp; CRUZ', $html);
    }

    private function generate(string $report = 'inventory'): ReportDataset
    {
        $filters = ReportFilters::fromRequest(Request::create('/reports'), $report, now()->startOfMonth(), now()->endOfMonth(), 'month');
        return app(ReportService::class)->generate($filters, $this->head);
    }

    private function fixtureDataset(int $count): ReportDataset
    {
        $base = $this->generate();
        return new ReportDataset('inventory', 'Inventory Status Report', [
            ['key' => 'item', 'label' => 'Item'],
            ['key' => 'quantity', 'label' => 'Quantity', 'align' => 'numeric'],
            ['key' => 'date', 'label' => 'Date'],
        ], collect(range(1, max(1, $count)))->take($count)->map(fn ($number) => [
            'item' => 'Fixture item '.$number, 'quantity' => (string) $number, 'date' => '16/11/2026',
        ]), meta: $base->meta);
    }

    private function exportFixture(ReportDataset $dataset, string $prefix): array
    {
        $outputs = [];
        foreach (['pdf', 'docx', 'xlsx', 'csv'] as $format) {
            $options = ReportExportOptions::fromRequest(Request::create('/reports/export', 'GET', ['format' => $format]), $dataset->reportKey);
            $outputs[$format] = app(ReportService::class)->renderExport($dataset, $options);
            if ($directory = getenv('REPORT_MANUAL_SIGNATORY_EVIDENCE_DIR')) {
                if (! is_dir($directory)) mkdir($directory, 0777, true);
                file_put_contents($directory.'/'.$prefix.'.'.$format, $outputs[$format]);
            }
        }
        return $outputs;
    }

    private function zipPart(string $bytes, string $part): string
    {
        $file = tempnam(sys_get_temp_dir(), 'report-manual-zip-');
        $zip = new ZipArchive;
        try {
            file_put_contents($file, $bytes);
            $this->assertTrue($zip->open($file));
            return (string) $zip->getFromName($part);
        } finally {
            $zip->close();
            @unlink($file);
        }
    }
}
